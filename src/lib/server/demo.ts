import { createUIMessageStream, createUIMessageStreamResponse } from "ai";
import type { ChatMessage } from "../chat-schema";
import { findModel, type ModelId } from "../models";
export function demoResponse(modelId: ModelId, signal: AbortSignal) {
  const text = `## A little room for a big idea\n\nYou’re trying **Numbase AI** in demo mode. This is a sample response, not an answer generated by ${findModel(modelId)?.name}.\n\nYour workspace is ready for:\n\n- **A model for every task** — switch providers without leaving the conversation.\n- **A clearer conversation** — formatted answers, tables, and highlighted code.\n- **Your own rhythm** — saved chats, light and dark themes, and streaming you can stop.\n\n\`\`\`typescript\nconst idea = "Something worth exploring";\nconsole.log(idea);\n\`\`\`\n\nTo receive real answers, add your OpenRouter key to the server’s \`.env.local\` file and restart the app. The key stays on the server.\n\n*What will you make next?*`;
  return createUIMessageStreamResponse({ headers: { "Cache-Control": "no-store" }, stream: createUIMessageStream<ChatMessage>({
    async execute({ writer }) {
      writer.write({ type: "start", messageId: crypto.randomUUID(), messageMetadata: { modelId, demo: true, createdAt: Date.now() } });
      writer.write({ type: "text-start", id: "demo" });
      for (const delta of text.match(/[\s\S]{1,14}/g) ?? []) {
        if (signal.aborted) { writer.setOutcome({ status: "aborted" }); return; }
        writer.write({ type: "text-delta", id: "demo", delta });
        await new Promise((resolve) => setTimeout(resolve, 22));
      }
      writer.write({ type: "text-end", id: "demo" });
      writer.write({ type: "finish", finishReason: "stop" });
      writer.setOutcome({ status: "completed" });
    }, onError: () => "The response was interrupted. Please try again.",
  }) });
}
